//! Conformance: `Oversampled2x` (the FIR half-band pairs) against the
//! world-class limits — flatness, transparency, latency exactness, and
//! alias rejection versus a Butterworth IIR oversampler.

use stave_dsp::{Biquad, FilterSpec, Oversampled2x, Stage};
use stave_measure::tone_window::ToneWindow;

/// The interior that passes its input through.
struct Identity;
impl Stage for Identity {
    fn tick(&mut self, x: f32) -> f32 {
        x
    }
}

/// The Butterworth IIR 2× oversampler the FIR pairs replaced: a 12th-order
/// cascade at 0.45·fs on each side of the interior — the reference the
/// rejection claim is measured against.
struct IirOversampler {
    up: [Biquad; 6],
    down: [Biquad; 6],
}

impl IirOversampler {
    fn new(sample_rate: f32) -> Self {
        let section = |k: usize| {
            let theta = (2.0 * k as f32 + 1.0) * core::f32::consts::PI / 24.0;
            let mut bq = Biquad::default();
            bq.prepare(2.0 * sample_rate);
            bq.set(FilterSpec::Lowpass {
                hz: 0.45 * sample_rate,
                q: 1.0 / (2.0 * theta.cos()),
            });
            bq
        };
        Self {
            up: core::array::from_fn(section),
            down: core::array::from_fn(section),
        }
    }

    fn run(stages: &mut [Biquad; 6], mut x: f32) -> f32 {
        for s in stages.iter_mut() {
            x = s.tick(x);
        }
        x
    }

    fn tick_with(&mut self, x: f32, mut inner: impl FnMut(f32) -> f32) -> f32 {
        let u0 = Self::run(&mut self.up, 2.0 * x);
        let u1 = Self::run(&mut self.up, 0.0);
        let (p0, p1) = (inner(u0), inner(u1));
        let _ = Self::run(&mut self.down, p0);
        Self::run(&mut self.down, p1)
    }
}

/// Check: passband deviation of the full up+down round trip, 20 Hz–20 kHz,
/// at the TIGHTEST rate (44.1 kHz — 20 kHz is 0.907 of Nyquist there).
/// The old Butterworth chain drooped ~1.3 dB at the top; the claim for
/// the FIR is ±0.1 dB.
#[test]
fn fir_round_trip_flat_to_20k_at_44k1_and_48k() {
    for fs in [44_100.0f64, 48_000.0] {
        let n = 8192usize;
        // Bins spanning 20 Hz .. ~20 kHz (bin-centred; top bin chosen
        // just under 20 kHz for the given rate).
        let top = (19_990.0 * n as f64 / fs) as usize;
        let bins = [4usize, 19, 93, 465, 930, 1861, 2791, 3200, top];
        let mut worst = 0.0f64;
        let mut worst_hz = 0.0f64;
        for &m in &bins {
            let mut os = Oversampled2x::front(Identity);
            os.prepare(fs as f32);
            let g = ToneWindow {
                bin: m,
                window: n,
                sample_rate: fs,
                amplitude: 0.5,
                warmup_windows: 1,
            }
            .gain_db(|x: f32| os.tick(x));
            let hz = m as f64 * fs / n as f64;
            if g.abs() > worst {
                worst = g.abs();
                worst_hz = hz;
            }
        }
        println!("fs {fs}: worst round-trip deviation {worst:.4} dB @ {worst_hz:.0} Hz");
        assert!(
            worst < 0.1,
            "not flat at fs {fs}: {worst:.3} dB @ {worst_hz:.0} Hz"
        );
    }
}

/// Check: identity round trip through the NESTED 4× stack is transparent —
/// audible-band non-harmonic residue ≤ −110 dB on a mid-band tone, and
/// the total latency is exactly the 84 samples the stack reports
/// (66 outer + 18 inner, at the base rate).
#[test]
fn nested_4x_is_transparent_with_exact_integer_latency() {
    let fs = 48_000.0;
    let n = 8192usize;
    let m = 171usize; // ~1002 Hz, bin-centred
    let stack = || Oversampled2x::front(Oversampled2x::nested(Identity));
    let mut os = stack();
    os.prepare(fs as f32);
    let r = ToneWindow {
        bin: m,
        window: n,
        sample_rate: fs,
        amplitude: 0.5,
        warmup_windows: 1,
    }
    .alias(|x: f32| os.tick(x));
    println!("nested 4× identity: audible floor {:.1} dB", r.audible_db);
    assert!(
        r.audible_db < -110.0,
        "4× stack not transparent: {:.1} dB",
        r.audible_db
    );

    // Latency: the impulse peaks at exactly the reported 66 + 18 = 84
    // base samples. A half-sample error would comb every wet/dry mix
    // downstream.
    let mut os = stack();
    os.prepare(fs as f32);
    let expected = os.latency() as usize;
    assert_eq!(expected, 84);
    let mut peak = (0usize, 0.0f32);
    for i in 0..4 * expected {
        let x = if i == 0 { 1.0 } else { 0.0 };
        let y = os.tick(x);
        if y.abs() > peak.1 {
            peak = (i, y.abs());
        }
    }
    assert_eq!(peak.0, expected, "nested latency {} != {expected}", peak.0);
    assert!(peak.1 > 0.9, "nested impulse peak too small: {}", peak.1);
}

/// The replacement claim, measured in isolation. A decimator's job is to
/// reject ultrasonic content (generated by the nonlinearity between the
/// filters) BEFORE it folds into the audible band. Confounds to avoid:
/// a raw hard clip at 2× aliases mostly AT the inner rate — a fold no
/// decimator can remove, which masks the filter difference entirely
/// (measured: FIR and IIR within 0.1 dB on that setup). So instead we
/// inject a known ultrasonic tone INSIDE the oversampled domain and
/// measure exactly what each decimator lets fold back.
///
/// Frequencies are chosen so the folds land in the 15–20 kHz audible
/// band — the region the Butterworth's transition shoulder leaks.
#[test]
fn fir_decimator_rejects_the_audible_fold_band() {
    let fs = 48_000.0;
    let n = 8192usize;
    let amp = 0.5f64;
    // Ultrasonic bins (inner-domain): 28.5 kHz → folds to 19.5 kHz,
    // 30 kHz → 18 kHz, 33 kHz → 15 kHz. All bin-exact: f = k·fs/n.
    for (k_us, label) in [
        (4864usize, "28.5 kHz→19.5 kHz"),
        (5120, "30 kHz→18 kHz"),
        (5632, "33 kHz→15 kHz"),
    ] {
        let f_us = k_us as f64 * fs / n as f64;
        let fold_hz = fs - f_us;
        let run = |fir: bool| -> f64 {
            // The interior passes the signal AND adds the ultrasonic tone
            // (phase-continuous via its own inner-rate counter).
            let mut osf = Oversampled2x::front(Inject {
                f_us,
                amp,
                inner_rate: 2.0 * fs,
                i: 0,
            });
            osf.prepare(fs as f32);
            let mut osb = IirOversampler::new(fs as f32);
            let mut inject = Inject {
                f_us,
                amp,
                inner_rate: 2.0 * fs,
                i: 0,
            };
            let out: Vec<f64> = (0..2 * n)
                .map(|_| {
                    if fir {
                        osf.tick(0.0) as f64
                    } else {
                        osb.tick_with(0.0, |x| inject.tick(x)) as f64
                    }
                })
                .skip(n)
                .collect();
            20.0 * (stave_measure::spectrum::goertzel(&out, fold_hz / fs) / amp).log10()
        };
        let fir_db = run(true);
        let iir_db = run(false);
        println!(
            "{label}: folded residue FIR {fir_db:.1} dB | IIR {iir_db:.1} dB (Δ {:+.1} dB)",
            iir_db - fir_db
        );
        assert!(fir_db < -85.0, "FIR lets {label} fold at {fir_db:.1} dB");
        assert!(
            fir_db < iir_db - 25.0,
            "FIR should beat IIR by ≥25 dB in the audible fold band: {fir_db:.1} vs {iir_db:.1}"
        );
    }
}

/// Adds a tone at `f_us` inside the oversampled domain.
struct Inject {
    f_us: f64,
    amp: f64,
    inner_rate: f64,
    i: usize,
}
impl Stage for Inject {
    fn tick(&mut self, x: f32) -> f32 {
        let t = self.i as f64 / self.inner_rate;
        self.i += 1;
        x + (self.amp * (2.0 * core::f64::consts::PI * self.f_us * t).sin()) as f32
    }
}
