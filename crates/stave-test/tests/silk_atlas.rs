//! Silk behaviour atlas — data dumps for offline plotting/analysis.
//!
//! Everything renders through the SHIPPED `SmoothSat` with Ember's exact
//! knob mappings (drive knob 3 → 2.05, warmth 0.35 → even 0.21, body
//! 0.2 → odd 0.12, silk knob → geometric decay-base taper), so the
//! numbers are the plugin's numbers, not a model's.
//!
//! Run:
//!   cargo test -p stave-test --release --test silk_atlas -- --ignored --nocapture
//!   python3 scripts/plot_silk_atlas.py     # → $TMPDIR/silk_atlas/*.png
//!
//! SILK_ATLAS_DIR overrides the output directory (both sides read it).
//!
//! What each dump answers:
//!  - kick_*.csv        — spectrogram source: does silk change what the
//!    LOW END generates over time on drum material?
//!  - transfer.csv      — the static waveshapes: is the difference a
//!    curve-shape difference (compression knee) or a filter?
//!  - gain_vs_level.csv — the gain-staging decomposition: small-signal
//!    gain, RMS gain, and PEAK gain vs input level per silk. If silk were
//!    "just gain staging" these lines would be parallel.
//!  - harmonics.csv     — per-fundamental harmonic budget: how much
//!    20–800 Hz content each silk position generates from each f0.
//!  - companding.csv    — proves the HF-smooth compander is not involved
//!    below 800 Hz (silk ≠ companding).
//!
//! The one enforced assertion: silk must NOT change the level driven
//! INTO the shaper (input staging is silk-independent by construction —
//! this pins it).

use std::fs;
use std::io::Write as _;

use stave_dsp::SmoothSat;
use stave_measure::spectrum::goertzel;

const FS: f64 = 48_000.0;
/// Where the CSVs go: $SILK_ATLAS_DIR, else <temp dir>/silk_atlas.
fn out_dir() -> String {
    std::env::var("SILK_ATLAS_DIR").unwrap_or_else(|_| {
        std::env::temp_dir().join("silk_atlas").to_string_lossy().into_owned()
    })
}

/// SmoothSat at Ember's default knob positions, at a given silk KNOB
/// value (the plugin's taper applied here, so labels match the UI).
fn ember_sat(silk_knob: f64, hf: f32) -> SmoothSat {
    let mut s = SmoothSat::new();
    s.prepare(FS as f32);
    s.set_drive(1.0 + 3.0 * 0.35);
    s.set_even(0.35 * 0.6);
    s.set_odd(0.2 * 0.6);
    // Keep in sync with Ember's silk mapping (geometric through the
    // floored decay base).
    let silk_eff = 1.0 - 0.043f64.powf(silk_knob);
    s.set_smoothness(silk_eff as f32);
    s.set_hf_smoothing(hf);
    s
}

/// Synthetic kick: pitch drop 90→55 Hz over ~20 ms, exponential amplitude
/// decay (τ = 125 ms), hits every 500 ms. Deterministic and band-limited
/// by construction — everything above the fundamental in the OUTPUT is
/// generated by the saturator.
fn kick_pattern(seconds: f64) -> Vec<f32> {
    let n = (FS * seconds) as usize;
    let mut out = vec![0.0f32; n];
    let hit_period = (FS * 0.5) as usize;
    for start in (0..n).step_by(hit_period) {
        let mut phase = 0.0f64;
        for i in 0..(FS * 0.45) as usize {
            let idx = start + i;
            if idx >= n {
                break;
            }
            let t = i as f64 / FS;
            let freq = 55.0 + 35.0 * (-t / 0.02).exp();
            phase += 2.0 * core::f64::consts::PI * freq / FS;
            let env = (-t * 8.0).exp();
            out[idx] += (0.9 * env * phase.sin()) as f32;
        }
    }
    out
}

fn write_csv(name: &str, header: &str, rows: &[Vec<f64>]) {
    let mut f = fs::File::create(format!("{}/{name}", out_dir())).expect("create csv");
    writeln!(f, "{header}").unwrap();
    for row in rows {
        let line: Vec<String> = row.iter().map(|v| format!("{v:.8}")).collect();
        writeln!(f, "{}", line.join(",")).unwrap();
    }
}

#[test]
#[ignore = "report: writes the atlas for scripts/plot_silk_atlas.py; run with --run-ignored only"]
fn silk_atlas_dump() {
    fs::create_dir_all(out_dir()).unwrap();
    let silks = [0.1f64, 0.5, 0.9];

    // ---- 1) Kick pattern time-domain (spectrogram source) ----
    let dry = kick_pattern(2.0);
    {
        let rows: Vec<Vec<f64>> = dry.iter().map(|&v| vec![v as f64]).collect();
        write_csv("kick_dry.csv", "y", &rows);
    }
    for &sk in &silks {
        let mut s = ember_sat(sk, 4.0);
        let rows: Vec<Vec<f64>> = dry.iter().map(|&v| vec![s.process(v) as f64]).collect();
        write_csv(&format!("kick_s{:03}.csv", (sk * 100.0) as u32), "y", &rows);
    }

    // ---- 2) Static transfer curves (drive applied, bias 0) ----
    {
        let drive = 1.0f32 + 3.0 * 0.35;
        let sats: Vec<SmoothSat> = silks.iter().map(|&sk| ember_sat(sk, 0.0)).collect();
        let mut rows = vec![];
        for i in 0..=640 {
            let x = -1.6 + 3.2 * i as f64 / 640.0;
            let mut row = vec![x];
            for s in &sats {
                row.push(s.shape(drive * x as f32) as f64);
            }
            rows.push(row);
        }
        write_csv("transfer.csv", "x,s010,s050,s090", &rows);
    }

    // ---- 3) Gain staging: RMS + peak gain vs input level, per silk ----
    // 60 Hz sine (exact integer cycles per second-long window).
    {
        let mut rows = vec![];
        for step in 0..=12 {
            let in_db = -36.0 + 3.0 * step as f64;
            let amp = 10f64.powf(in_db / 20.0);
            let mut row = vec![in_db];
            for &sk in &silks {
                let mut s = ember_sat(sk, 4.0);
                let n = FS as usize;
                let sig = |i: usize| {
                    (amp * (2.0 * core::f64::consts::PI * 60.0 * i as f64 / FS).sin()) as f32
                };
                for i in 0..n / 2 {
                    let _ = s.process(sig(i)); // settle DC blocker / shelves
                }
                let out: Vec<f64> = (n / 2..n + n / 2)
                    .map(|i| s.process(sig(i)) as f64)
                    .collect();
                let rms = (out.iter().map(|v| v * v).sum::<f64>() / out.len() as f64).sqrt();
                let peak = out.iter().fold(0.0f64, |m, v| m.max(v.abs()));
                let in_rms = amp / core::f64::consts::SQRT_2;
                row.push(20.0 * (rms / in_rms).log10()); // RMS gain dB
                row.push(20.0 * (peak / amp).log10()); // peak gain dB
            }
            rows.push(row);
        }
        write_csv(
            "gain_vs_level.csv",
            "in_db,rms_s010,peak_s010,rms_s050,peak_s050,rms_s090,peak_s090",
            &rows,
        );
    }

    // ---- 4) Harmonic budget per fundamental × silk ----
    // mud_db = Σ harmonics k ≥ 2 with k·f0 ≤ 800 Hz, relative to the
    // fundamental — "how much 20–800 Hz content does the low end spawn".
    {
        let mut rows = vec![];
        for &f0 in &[40.0f64, 60.0, 100.0, 200.0, 400.0] {
            for step in 0..=10 {
                let sk = step as f64 / 10.0;
                let mut s = ember_sat(sk, 4.0);
                let n = FS as usize; // 1 s → integer cycles for all f0 here
                let sig = |i: usize| {
                    (0.8 * (2.0 * core::f64::consts::PI * f0 * i as f64 / FS).sin()) as f32
                };
                for i in 0..n / 2 {
                    let _ = s.process(sig(i));
                }
                let out: Vec<f64> = (n / 2..n + n / 2)
                    .map(|i| s.process(sig(i)) as f64)
                    .collect();
                let h1 = goertzel(&out, f0 / FS).max(1e-12);
                let mut row = vec![f0, sk];
                let mut mud = 0.0f64;
                for k in 2..=10 {
                    let h = goertzel(&out, (k as f64 * f0) / FS);
                    row.push(20.0 * (h / h1).log10());
                    if k as f64 * f0 <= 800.0 {
                        mud += (h / h1).powi(2);
                    }
                }
                row.push(10.0 * mud.max(1e-24).log10());
                rows.push(row);
            }
        }
        write_csv(
            "harmonics.csv",
            "f0,silk,h2,h3,h4,h5,h6,h7,h8,h9,h10,mud_db",
            &rows,
        );
    }

    // ---- 5) Companding is not the LF mechanism ----
    {
        let mut rows = vec![];
        for &hf in &[0.0f32, 4.0, 10.0, 18.0] {
            let mut s = ember_sat(0.5, hf);
            let n = FS as usize;
            let sig = |i: usize| {
                (0.8 * (2.0 * core::f64::consts::PI * 60.0 * i as f64 / FS).sin()) as f32
            };
            for i in 0..n / 2 {
                let _ = s.process(sig(i));
            }
            let out: Vec<f64> = (n / 2..n + n / 2)
                .map(|i| s.process(sig(i)) as f64)
                .collect();
            let h1 = goertzel(&out, 60.0 / FS).max(1e-12);
            let mut mud = 0.0f64;
            for k in 2..=10 {
                let h = goertzel(&out, (k as f64 * 60.0) / FS);
                mud += (h / h1).powi(2);
            }
            rows.push(vec![hf as f64, 10.0 * mud.max(1e-24).log10()]);
        }
        write_csv("companding.csv", "hf_db,mud_db", &rows);
    }

    // ---- Enforced: silk does NOT touch input staging ----
    // The pre-shaper path (drive + HF shelf) must be bit-identical across
    // silk positions: whatever silk does, it is not "less level into the
    // sat".
    {
        let sig =
            |i: usize| (0.8 * (2.0 * core::f64::consts::PI * 60.0 * i as f64 / FS).sin()) as f32;
        let pre_rms = |sk: f64| -> f64 {
            let mut s = ember_sat(sk, 4.0);
            let mut acc = 0.0f64;
            for i in 0..24_000 {
                let p = s.process_pre(sig(i)) as f64;
                acc += p * p;
            }
            (acc / 24_000.0).sqrt()
        };
        let a = pre_rms(0.0);
        let b = pre_rms(0.9);
        assert!(
            (a - b).abs() < 1e-9,
            "silk must not change the level into the shaper: {a} vs {b}"
        );
        println!(
            "pre-shaper RMS identical across silk: {a:.6} (input staging is silk-independent ✓)"
        );
    }

    println!("silk atlas dumped to {}/ — plot with scripts/plot_silk_atlas.py", out_dir());
}
