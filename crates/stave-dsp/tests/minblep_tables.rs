//! Regenerates `src/primitives/osc/blep/tables.rs`, the minBLEP tables
//! as compile-time constants, from their design:
//!
//! ```sh
//! STAVE_BLESS=1 cargo test -p stave-dsp --test minblep_tables
//! ```
//!
//! Without `STAVE_BLESS` it does nothing; the library's own
//! `tables_match_their_design` holds the committed tables to the design.

#[test]
#[cfg_attr(miri, ignore = "writes a source file")]
fn regenerate_when_blessing() {
    if std::env::var_os("STAVE_BLESS").is_none() {
        return;
    }
    let (step, ramp, delay, len) = stave_dsp::primitives::osc::__minblep_design();
    let list = |v: &[f64]| v.iter().map(|x| format!("{x:?},")).collect::<Vec<_>>().join("\n    ");
    let text = format!(
        "// Generated by `STAVE_BLESS=1 cargo test -p stave-dsp --test minblep_tables`\n\
         // from the minBLEP design; held to it by `tables_match_their_design`.\n\
         // Do not edit.\n\n\
         pub(super) const DELAY: usize = {delay};\n\
         pub(super) const LEN: usize = {len};\n\n\
         pub(super) const STEP: &[f64] = &[\n    {}\n];\n\n\
         pub(super) const RAMP: &[f64] = &[\n    {}\n];\n",
        list(&step),
        list(&ramp)
    );
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/src/primitives/osc/blep/tables.rs");
    std::fs::write(path, text).expect("write blep/tables.rs");
}
